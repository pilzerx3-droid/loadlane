import { randomBytes } from "node:crypto";
import { schema, withTenant } from "@loadlane/db";
import { count, eq } from "drizzle-orm";
import type pg from "pg";
import { pgErrorInfo } from "../../platform/pg-error.ts";
import {
  slugify,
  type CreateOrganizationInput,
  type OrganizationResponse,
} from "./organization.schemas.ts";

/** The person has created as many organizations as the limit allows. */
export class OrganizationLimitReachedError extends Error {
  constructor(readonly limit: number) {
    super(`You can create at most ${limit} organizations`);
    this.name = "OrganizationLimitReachedError";
  }
}

/** The short name is taken by another organization. */
export class SlugTakenError extends Error {
  constructor() {
    super("This short name is already taken");
    this.name = "SlugTakenError";
  }
}

const MAX_SLUG_ATTEMPTS = 5;

/**
 * Creates an organization with its first admin, in one transaction under row-level security: the
 * organization, the active membership, the admin role and the audit entry succeed or fail together.
 * The limit per person is checked inside the transaction behind a per-person lock, so parallel
 * requests cannot exceed it.
 */
export class OrganizationCreator {
  constructor(
    private readonly pool: pg.Pool,
    private readonly maxPerUser: number,
  ) {}

  async create(
    userId: string,
    input: CreateOrganizationInput,
    requestId: string | undefined,
  ): Promise<OrganizationResponse> {
    const explicitSlug = input.slug !== undefined;
    const base = input.slug ?? slugify(input.name);

    for (let attempt = 0; attempt < MAX_SLUG_ATTEMPTS; attempt++) {
      // A name derived from the display name gets a random suffix when it collides.
      const slug = attempt === 0 ? base : `${base.slice(0, 40)}-${randomBytes(2).toString("hex")}`;
      try {
        return await this.createOnce(userId, input, slug, requestId);
      } catch (error) {
        const { code, constraint } = pgErrorInfo(error);
        if (code === "23505" && constraint === "organization_slug_key") {
          if (explicitSlug) throw new SlugTakenError();
          continue;
        }
        throw error;
      }
    }
    throw new SlugTakenError();
  }

  private async createOnce(
    userId: string,
    input: CreateOrganizationInput,
    slug: string,
    requestId: string | undefined,
  ): Promise<OrganizationResponse> {
    // The id is generated by the database (UUID v7). The insert policy requires it to equal the
    // organization in the transaction context, so it is fetched first.
    const generated = await this.pool.query<{ id: string }>("SELECT uuidv7()::text AS id");
    const organizationId = generated.rows[0]?.id;
    if (!organizationId) throw new Error("The database did not return an id");

    return withTenant(this.pool, { organizationId, userId }, async ({ db, client }) => {
      await client.query("SELECT pg_advisory_xact_lock(hashtextextended($1, 0))", [
        `organization-create:${userId}`,
      ]);

      const [created] = await db
        .select({ total: count() })
        .from(schema.organization)
        .where(eq(schema.organization.createdByUserId, userId));
      if ((created?.total ?? 0) >= this.maxPerUser) {
        throw new OrganizationLimitReachedError(this.maxPerUser);
      }

      const [organization] = await db
        .insert(schema.organization)
        .values({
          id: organizationId,
          name: input.name,
          slug,
          timezone: input.timezone,
          createdByUserId: userId,
        })
        .returning({
          id: schema.organization.id,
          name: schema.organization.name,
          slug: schema.organization.slug,
          region: schema.organization.region,
          distanceUnit: schema.organization.distanceUnit,
          weightUnit: schema.organization.weightUnit,
          currency: schema.organization.currency,
          locale: schema.organization.locale,
          timezone: schema.organization.timezone,
        });
      const [membership] = await db
        .insert(schema.membership)
        .values({ organizationId, userId, status: "active" })
        .returning({ id: schema.membership.id });
      if (!organization || !membership) throw new Error("The organization was not created");

      await db
        .insert(schema.membershipRole)
        .values({ organizationId, membershipId: membership.id, roleKey: "admin" });
      // OPEN (legal, ADR 0002): ip and user agent are not recorded until their retention is decided.
      await db.insert(schema.auditLog).values({
        organizationId,
        actorType: "user",
        actorUserId: userId,
        action: "organization.created",
        entityType: "organization",
        entityId: organizationId,
        changes: { name: input.name, slug, timezone: input.timezone },
        ...(requestId === undefined ? {} : { requestId }),
      });
      return organization;
    });
  }
}
