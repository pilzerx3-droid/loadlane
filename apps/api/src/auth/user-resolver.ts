import { schema, withTenant } from "@loadlane/db";
import { and, eq } from "drizzle-orm";
import type pg from "pg";
import type { VerifiedToken } from "./token-verifier.ts";
import type { UserInfo, UserInfoSource } from "./userinfo.ts";

export interface ResolvedUser {
  id: string;
  email: string;
  displayName: string;
}

/** The provider does not vouch for the e-mail address, so no account is created. */
export class EmailNotVerifiedError extends Error {
  constructor() {
    super("The e-mail address is not verified at the sign-in provider");
    this.name = "EmailNotVerifiedError";
  }
}

/** The address belongs to an account with a different sign-in identity. Never linked automatically. */
export class EmailAlreadyRegisteredError extends Error {
  constructor() {
    super("The e-mail address is already registered with a different sign-in identity");
    this.name = "EmailAlreadyRegisteredError";
  }
}

export class UserDeactivatedError extends Error {
  constructor() {
    super("The account is deactivated");
    this.name = "UserDeactivatedError";
  }
}

interface PgErrorShape {
  code?: string;
  constraint?: string;
}

/** Drizzle wraps driver errors; look at the error itself and at its cause. */
function pgError(error: unknown): PgErrorShape {
  const candidate = error as { cause?: unknown } & PgErrorShape;
  return typeof candidate.cause === "object" && candidate.cause !== null
    ? candidate.cause
    : candidate;
}

/**
 * Turns a verified token into one of our users. Identifies people only by (issuer, subject).
 * Registers a new person on first sign-in, but only with an e-mail address the provider has verified,
 * and never links an existing account by e-mail address (account takeover risk, ADR 0003).
 */
export class UserResolver {
  constructor(
    private readonly pool: pg.Pool,
    private readonly userInfo: UserInfoSource,
  ) {}

  async resolve(token: VerifiedToken, accessToken: string): Promise<ResolvedUser> {
    const existing = await this.find(token);
    if (existing) return existing;

    const info = await this.userInfo.fetch(accessToken, token.subject);
    if (!info.emailVerified) throw new EmailNotVerifiedError();
    return this.register(token, info);
  }

  private async find(token: VerifiedToken): Promise<ResolvedUser | undefined> {
    const rows = await withTenant(
      this.pool,
      { authIssuer: token.issuer, authSubject: token.subject },
      ({ db }) =>
        db
          .select({
            id: schema.appUser.id,
            email: schema.appUser.email,
            displayName: schema.appUser.displayName,
            deactivatedAt: schema.appUser.deactivatedAt,
          })
          .from(schema.appUser)
          .where(
            and(
              eq(schema.appUser.authIssuer, token.issuer),
              eq(schema.appUser.authSubject, token.subject),
            ),
          )
          .limit(1),
    );
    const row = rows[0];
    if (!row) return undefined;
    if (row.deactivatedAt) throw new UserDeactivatedError();
    return { id: row.id, email: row.email, displayName: row.displayName };
  }

  private async register(token: VerifiedToken, info: UserInfo): Promise<ResolvedUser> {
    // The id is generated by the database (UUID v7). The insert policy requires it to equal the
    // user id in the transaction context, so it is fetched first.
    const generated = await this.pool.query<{ id: string }>("SELECT uuidv7()::text AS id");
    const id = generated.rows[0]?.id;
    if (!id) throw new Error("The database did not return an id");

    const displayName = info.name ?? info.email;
    try {
      await withTenant(
        this.pool,
        { userId: id, authIssuer: token.issuer, authSubject: token.subject },
        ({ db }) =>
          db.insert(schema.appUser).values({
            id,
            email: info.email,
            displayName,
            authIssuer: token.issuer,
            authSubject: token.subject,
          }),
      );
    } catch (error) {
      const { code, constraint } = pgError(error);
      const duplicate =
        code === "23505" &&
        (constraint === "app_user_email_key" || constraint === "app_user_auth_identity_key");
      if (!duplicate) throw error;

      // PostgreSQL reports whichever unique index it checks first, so a parallel first request of the
      // same person can surface as an e-mail conflict. Look the identity up before deciding.
      const existing = await this.find(token);
      if (existing) return existing;
      if (constraint === "app_user_email_key") throw new EmailAlreadyRegisteredError();
      throw error;
    }
    return { id, email: info.email, displayName };
  }
}
